export type Key = keyof typeof fr;

const texts: Record<Lang, typeof fr> = { fr, en, de };

export const langOf = (hass: HomeAssistant): Lang =>
  hass.language?.startsWith("fr") ? "fr" : hass.language?.startsWith("de") ? "de" : "en";

/** Locale for number and date formats. */
export const localeOf = (hass: HomeAssistant): string => hass.locale?.language ?? hass.language ?? "en";

export function t(lang: Lang, key: Key, vars: Record<string, string> = {}): string {
  return texts[lang][key].replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

/** Readable message key for a websocket error. */
export function errorKey(err: unknown): Key {
  const code = (err as { code?: string })?.code;
  if (code === "not_loaded") return "not_loaded";
  if (code === "invalid" || code === "in_progress" || code === "not_found") return `err_${code}`;
  return "error";
}
